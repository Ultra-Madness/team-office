// Regenerates src/office.tsx (code) and public/data.json (data) from the Page source.
// Usage: node scripts/sync-from-canvas.mjs /path/to/canvas.tsx
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { transformSync } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(process.argv[2] || "canvas.tsx", "utf8");
const cut = (a, b) => { const i = src.indexOf(a); const j = src.indexOf(b, i); if (i < 0 || j < 0) throw new Error(`marker missing: ${a} / ${b}`); return src.slice(i, j); };

// Data: PROJECT, BOARD, OFFICE, MESSAGES (BOARD_COLS..PHASES are code, kept in office.tsx).
const dataSrc = cut("const PROJECT = {", "const BOARD_COLS") + cut("const OFFICE = {", "const REPLAY_LAST");
const js = transformSync(dataSrc + "\nexport default { PROJECT, BOARD, OFFICE, MESSAGES };", { loader: "ts", format: "cjs" }).code;
const mod = { exports: {} };
new Function("module", "exports", js)(mod, mod.exports);
const data = mod.exports.default;
data.lastUpdated = data.OFFICE.asOf;
data.links = data.OFFICE.links || [];
fs.writeFileSync(path.join(root, "public/data.json"), JSON.stringify(data, null, 2) + "\n");

// Code: everything else, wrapped in a factory that takes the data.
const consts = cut("const BOARD_COLS", "const OFFICE = {");
const rest = src.slice(src.indexOf("const REPLAY_LAST")).replace("export default function App()", "function App()");
const office = `// GENERATED by scripts/sync-from-canvas.mjs from the Team Office Page source. Do not edit by hand.
import { useGrokTheme, useState, useEffect, useRef } from "./kit";

export function makeOffice(D: any) {
const PROJECT: any = D.PROJECT;
const BOARD: any = D.BOARD;
const OFFICE: any = D.OFFICE;
const MESSAGES: any[] = D.MESSAGES;
${consts}
${rest}
return App;
}
`;
fs.writeFileSync(path.join(root, "src/office.tsx"), office);
console.log(`data.json: ${data.MESSAGES.length} messages, ${data.BOARD.cards.length} cards, last updated ${data.lastUpdated}`);
